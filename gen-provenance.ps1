#Requires -Version 5.1
<#
.SYNOPSIS
    Draft a PROVENANCE manifest from your actual dsh plugin list. Parses the
    flat plugin tree, optionally enriches each package with license/repository
    from the npm registry (-Online), and writes PROVENANCE.draft.md next to
    this script. Never overwrites an existing PROVENANCE.md - you merge.

.EXAMPLE
    .\gen-provenance.ps1                     # offline draft
    .\gen-provenance.ps1 -Online             # fill license/source from npm
#>
[CmdletBinding()]
param(
    [string]$Profile = "desktop",
    [string]$OutFile,
    [switch]$Online
)

$ErrorActionPreference = "Stop"
$hub = $PSScriptRoot

# ---------- locate dsh CLI ----------
$configPath = Join-Path $hub "config.ps1"
$DshCli = $null; $DshProfile = $null
if (Test-Path $configPath) { . $configPath }
if (-not $DshCli) { $DshCli = (Get-Command dsh -ErrorAction SilentlyContinue).Source }
if (-not $DshCli) {
    foreach ($p in @(
        "$env:LOCALAPPDATA\Programs\deepseek harness\resources\runtime\cli\bin\dsh.cmd",
        "D:\Program Files (x86)\deepseek harness\resources\runtime\cli\bin\dsh.cmd",
        "C:\Program Files\deepseek harness\resources\runtime\cli\bin\dsh.cmd"
    )) { if (Test-Path $p) { $DshCli = $p; break } }
}
if (-not $DshCli -or -not (Test-Path $DshCli)) { throw "dsh CLI not found; set `$DshCli in config.ps1" }
if (-not $Profile) { $Profile = $(if ($DshProfile) { $DshProfile } else { "desktop" }) }

# ---------- run `dsh plugin list --depth=0` with clean UTF-8 decoding ----------
$psi = New-Object System.Diagnostics.ProcessStartInfo
$psi.FileName = $DshCli
$psi.Arguments = "plugin --profile $Profile list --depth=0"
$psi.RedirectStandardOutput = $true
$psi.RedirectStandardError = $true
$psi.UseShellExecute = $false
$psi.StandardOutputEncoding = [System.Text.Encoding]::UTF8
$proc = [System.Diagnostics.Process]::Start($psi)
$out = $proc.StandardOutput.ReadToEnd()
$proc.WaitForExit()

# ---------- parse name@version (or name@link:path) ----------
$pkgs = @()
$rx = [regex]'(^|\s)(?<name>@[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+|[A-Za-z0-9_.-]+)@(?<ver>\S+)'
foreach ($line in ($out -split "`r?`n")) {
    if ($line -match "packages\s*$") { continue }
    if ($line -match "Legend|PRIVATE") { continue }
    $m = $rx.Match($line)
    if ($m.Success) {
        $pkgs += [pscustomobject]@{
            Name    = $m.Groups["name"].Value
            Version = $m.Groups["ver"].Value
        }
    }
}
# de-duplicate, keep first occurrence (top-level listing)
$pkgs = $pkgs | Group-Object Name | ForEach-Object { $_.Group[0] }
if (-not $pkgs) { throw "no packages parsed - dsh output format changed?"; }

# ---------- optional npm enrichment ----------
foreach ($p in $pkgs) {
    $p | Add-Member -NotePropertyName License -NotePropertyValue "?"
    $p | Add-Member -NotePropertyName Source -NotePropertyValue "?"
    if ($p.Version -like "link:*") {
        $p.Source = "local link: " + $p.Version.Substring(5)
        $p.License = "(local)"
        continue
    }
    if ($Online) {
        try {
            $meta = npm view $p.Name license repository.url version 2>$null
            if ($LASTEXITCODE -eq 0 -and $meta) {
                $lines = @($meta | Where-Object { $_ -and $_.Trim() })
                if ($lines.Count -ge 1) { $p.License = $lines[0].Trim() }
                if ($lines.Count -ge 3) { $p.Source = $lines[$lines.Count - 1].Trim() }
            }
        } catch { }
    }
}

# ---------- emit draft ----------
if (-not $OutFile) { $OutFile = Join-Path $hub "PROVENANCE.draft.md" }
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# PROVENANCE draft - auto-generated $(Get-Date -Format 'yyyy-MM-dd HH:mm')")
[void]$sb.AppendLine("")
[void]$sb.AppendLine('Environment: dsh profile "' + $Profile + '", ' + $pkgs.Count + ' top-level packages.')
[void]$sb.AppendLine("Generated by gen-provenance.ps1$(if ($Online) { ' (npm-enriched)' }). Merge into PROVENANCE.md after filling the Verified column.")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("## Installed Cordis plugins (profile: $Profile)")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("| Plugin | Version | Source | License | Verified how |")
[void]$sb.AppendLine("| --- | --- | --- | --- | --- |")
foreach ($p in $pkgs) {
    [void]$sb.AppendLine('| `' + $p.Name + '` | ' + $p.Version + ' | ' + $p.Source + ' | ' + $p.License + ' | TODO |')
}
[void]$sb.AppendLine("")
[void]$sb.AppendLine("## Still to fill by hand")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("- [ ] Verified how: one line per plugin (e.g. 'tool appears in session; ran /command')")
[void]$sb.AppendLine("- [ ] Skills-type tools section (copy from templates/PROVENANCE.template.md)")
[void]$sb.AppendLine("- [ ] Not-installed/refused list with reasons")
[void]$sb.AppendLine("- [ ] Model integrity notes (file, size, SHA256, source manifest)")
[System.IO.File]::WriteAllText($OutFile, $sb.ToString(), (New-Object System.Text.UTF8Encoding($true)))

Write-Host ("draft written: {0} ({1} packages)" -f $OutFile, $pkgs.Count)
if (Test-Path (Join-Path $hub "PROVENANCE.md")) {
    Write-Host "PROVENANCE.md already exists - merge the draft into it (not overwritten)."
}
